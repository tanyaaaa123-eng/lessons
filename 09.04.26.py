# Определите количество троек элементов последовательности,
# в которых не более двух из трёх элементов являются двузначными числами,
# а сумма элементов тройки не превосходит сумму минимального двузначного
# и максимального двузначного элементов последовательности.
#
# В ответе запишите количество найденных троек чисел,
# затем максимальную из сумм элементов таких троек.
# В данной задаче под тройкой подразумевается три идущих подряд элемента последовательности.
with open("1717.txt")as f:
    line = list(map(int,f))
maxx = max(i for i in line if 9<abs(i)<100)
minn = min(i for i in line if 9<abs(i)<100)
s = (maxx)+(minn)
l = []
for a,b,c in zip(line,line[1:],line[2:]):
    n = 0
    if 9 < abs(a) < 100:
        n += 1
    if 99 < abs(b) < 100:
        n += 1
    if 9 < abs(c) < 100:
        n += 1
    if n <= 2 and (a+b+c)<=s:
        l.append(a + b + c)
print(len(l), max(l))


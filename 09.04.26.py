with open("1714.txt")as f:
    line = list(map(int,f))
p= max(i for i in line if abs(i)%100==25)
l = []
for a,b,c in zip(line,line[1:],line[2:]):
    n = 0
    if 999<abs(a)<10000:
        n+=1
    if 999<abs(b)<10000:
        n+=1
    if 999 <abs(c)< 10000:
        n += 1
    if n<=2 and (a+b+c)<=p:
        l.append(a+b+c)
print(len(l),max(l))

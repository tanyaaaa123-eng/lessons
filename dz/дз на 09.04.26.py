#
# Определите количество троек элементов последовательности, в которых хотя бы
# один из трёх элементов оканчивается на 3,
# а сумма элементов тройки не больше максимального элемента последовательности,
# являющегося пятизначным числом, которое оканчивается на 3.
with open("1703.txt") as f:
    line = list(map(int,f))
c = []
for i in line:
    if 9999<abs(i)<100000 and abs(i)%10==3:
        c.append(i)
c1 = max(c)
n = []
for a,b,c in zip(line,line[1:],line[2:]):
    if abs(a)%10 == 3 or abs(b)%10 ==3 or abs(c)%10==3 and (a+b+c)<=c1:
        n.append(a+b+c)
print(len(n),max(n))

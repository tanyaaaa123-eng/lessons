# 1.В файле 1705 содержится последовательность целых чисел.
# Её элементы могут принимать целые значения от –100 000 до 100 000 включительно.
#
# Определите количество пар последовательности, в которых хотя бы одно число отрицательно,
# а сумма чисел пары меньше количества чисел последовательности, кратных 32.
#
# Выведите на экран количество найденных пар, затем максимальную из сумм элементов таких пар.
# В данной задаче под парой подразумевается два идущих подряд элемента последовательности.
with open("1705.txt")as f:
    line = list(map(int,f))
c = []
for i in line:
    if i%32==0:
        c.append(i)
a = []
for el1,el2 in zip(line,line[1:]):
    if (el1<0 or el2<0) and (el1+el2)<len(c):
        a.append(el1+el2)
print(len(a),max(a))

# В магазине для упаковки подарков есть N кубических коробок.
# Самой интересной считается упаковка подарка по принципу матрёшки –
# подарок упаковывается в одну из коробок, та, в свою очередь,
# в другую коробку и т.д. Одну коробку можно поместить в другую,
# если длина её стороны меньше длины стороны другой коробки не
# менее чем на 9 единиц.
# Определите наибольшее количество коробок, которое можно использовать
# для упаковки одного подарка, и максимально возможную длину стороны
# самой маленькой коробки, где будет находиться подарок.
# Размер подарка позволяет поместить его в самую маленькую коробку.
#
# Входные данные
# В первой строке файла 2601 находится число N – количество коробок
# в магазине (натуральное число, не превышающее 10 000). В следующих
# N строках находятся значения длин сторон коробок (все числа натуральные,
# не превышающие 10 000), каждое – в отдельной строке.
#
# Запишите в ответе два целых числа: сначала наибольшее количество коробок,
# которое можно использовать для упаковки одного подарка, затем максимально
# возможную длину стороны самой маленькой коробки в таком наборе
with open("2601.txt")as f:
    N=int(f.readline())
    a = list(map(int,f))
d=sorted(a,reverse=True)
res=[d[0]]
for i in d[1:]:
    if res[-1]-i >=9 :
        res.append(i)
print(len(res),min(res))

#
# Если время окончания одного мероприятия совпадает со временем
# начала другого, то провести можно оба.
#
# Определите, какое максимальное количество мероприятий
# можно провести в конференц-зале и каков при этом максимально
# возможный перерыв между двумя последними мероприятиями.
#
# Входные данные
#
# В первой строке входного файла находится натуральное число N
# (N ≤ 1000) – количество заявок на проведение мероприятий.
# Следующие N строк содержат пары чисел, обозначающих время
# начала и время окончания мероприятий. Каждое из чисел натуральное,
# не превосходящее 1440.
#
# Запишите в ответе два числа: максимальное количество мероприятий и
# самый длинный перерыв между двумя последними мероприятиями (в минутах).
